/**
 * @file Generate real source declaration/parameter anchors across the workbench and original engine.
 * @description TypeScript AST indexes TS/JS/CJS declarations; Python tool definitions use explicit source-line syntax.
 * @exports No runtime API; --check compares the exact formatted source index without changing it.
 */
import ts from 'typescript';
import prettier from 'prettier';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
import process from 'node:process';
import console from 'node:console';
const root = resolve(import.meta.dirname, '..');
const roots = ['src', 'dashboard', 'desktop', 'scripts', 'tests'];
const output = resolve(root, 'docs/code-map.md');
const excluded = new Set(['node_modules', '__pycache__', 'public']);

async function files(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (excluded.has(entry.name)) continue;
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) result.push(...(await files(path)));
    else if (entry.isFile() && /\.(?:ts|js|mjs|cjs|py)$/.test(path)) result.push(path);
  }
  return result;
}
function declarations(path, source) {
  const rows = [];
  if (path.endsWith('.py')) {
    for (const [index, line] of source.split(/\r?\n/).entries()) {
      const match = line.match(
        /^\s*(?:async\s+)?(?:def|class)\s+([A-Za-z_][A-Za-z0-9_]*)|^\s*([A-Z][A-Z0-9_]+)\s*=/,
      );
      if (match) rows.push([match[1] ? 'definition' : 'constant', match[1] ?? match[2], index + 1]);
    }
    return rows;
  }
  const tree = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true);
  function binding(node, kind) {
    if (ts.isIdentifier(node) || ts.isPrivateIdentifier(node) || ts.isStringLiteral(node))
      rows.push([
        kind,
        node.text,
        tree.getLineAndCharacterOfPosition(node.getStart(tree)).line + 1,
      ]);
    else if (ts.isObjectBindingPattern(node) || ts.isArrayBindingPattern(node))
      for (const item of node.elements) if (ts.isBindingElement(item)) binding(item.name, kind);
  }
  function visit(node) {
    if (ts.isVariableDeclaration(node)) binding(node.name, 'variable');
    else if (ts.isParameter(node)) binding(node.name, 'parameter');
    else if (
      ts.isFunctionDeclaration(node) ||
      ts.isClassDeclaration(node) ||
      ts.isInterfaceDeclaration(node) ||
      ts.isTypeAliasDeclaration(node) ||
      ts.isEnumDeclaration(node)
    ) {
      if (node.name) binding(node.name, 'declaration');
    } else if (
      ts.isMethodDeclaration(node) ||
      ts.isPropertyDeclaration(node) ||
      ts.isGetAccessorDeclaration(node) ||
      ts.isSetAccessorDeclaration(node)
    )
      binding(node.name, 'member');
    ts.forEachChild(node, visit);
  }
  visit(tree);
  return rows;
}
const sections = [];
for (const path of (await Promise.all(roots.map((name) => files(resolve(root, name)))))
  .flat()
  .sort()) {
  const rows = declarations(path, await readFile(path, 'utf8'));
  if (!rows.length) continue;
  sections.push(
    `## \`${relative(root, path).replaceAll('\\', '/')}\`\n\n| Kind | Declaration | Line |\n|---|---|---:|\n${rows.map(([kind, name, line]) => `| ${kind} | \`${name}\` | ${line} |`).join('\n')}`,
  );
}
const text = await prettier.format(
  `# Source code map\n\nGenerated by \`node scripts/generate-code-map.mjs\`; declaration and parameter lines refer to current authored source. TS/JS uses the actual TypeScript AST. Python packaging-tool definitions/constants are indexed from explicit source lines. File headers and the file catalog explain responsibilities and operating boundaries.\n\n${sections.join('\n\n')}\n`,
  { ...(await prettier.resolveConfig(output)), parser: 'markdown' },
);
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== text) throw new Error('Source code map is stale.');
} else await writeFile(output, text, 'utf8');
console.log('Source declaration map is current.');
