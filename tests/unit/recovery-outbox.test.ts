/** Independent typed measurement fixture with source time unrelated to enqueue time. */
function metric(value = 1): Metric {
  return {
    name: 'cargo.temperature',
    value,
    dataType: 'float64',
    quality: 'good',
    sourceTimestamp: '2026-01-15T12:00:00.000Z',
    unit: 'celsius',
  };
}
/** Handwritten valid checkpoint, not generated by the implementation being tested. */
function checkpoint(): Checkpoint {
  return {
    schemaVersion: 'outbox-1',
    groupId: 'cold-chain',
    nodeId: 'van-07',
    capturedAt: 30,
    birthSequence: 7,
    currentMetrics: [metric(0)],
    lastOrdinal: 5,
    entries: [
      { ordinal: 2, enqueuedAt: 10, expiresAt: 40, metrics: [metric(2)] },
      { ordinal: 4, enqueuedAt: 20, expiresAt: 100, metrics: [metric(4)] },
      { ordinal: 5, enqueuedAt: 30, expiresAt: 110, metrics: [metric(5)] },
    ],
  };
}
/** Isolated node plus real lab consumer with explicit shared time. */
function harness(capacity = 4, ttlMs = 1000) {
  let now = 30;
  const broker = new InMemoryBroker();
  broker.registerCredential('fixture', 'fictional', {
    role: 'node',
    groupId: 'cold-chain',
    nodeId: 'van-07',
  });
  broker.registerCredential('reader', 'fictional', { role: 'consumer', groupId: 'cold-chain' });
  const configuration = {
    clientId: 'van',
    groupId: 'cold-chain',
    nodeId: 'van-07',
    outboxCapacity: capacity,
    outboxTtlMs: ttlMs,
    overflowPolicy: 'drop-oldest' as const,
    username: 'fixture',
    password: 'fictional',
  };
  const clock = () => new Date(now);
  const node = new EdgeNode(broker, configuration, clock, createDeterministicIdFactory(1000));
  const consumer = new StateConsumer({
    broker,
    clock,
    clientId: 'monitor',
    groupId: 'cold-chain',
    username: 'reader',
    password: 'fictional',
  });
  return {
    node,
    broker,
    consumer,
    setTime: (time: number) => {
      now = time;
    },
  };
}

describe('TTL recovery queue', () => {
  it.each([0, 1001, 1.5, NaN])('rejects capacity %s', (capacity) => {
    expect(() => new RecoveryOutbox(capacity, 'drop-oldest')).toThrow();
  });
  it.each([0, 86400001, 0.5])('rejects TTL %s', (ttl) => {
    expect(() => new RecoveryOutbox(2, 'drop-oldest', ttl)).toThrow();
  });
  it('rejects a non-enumerated policy at runtime', () => {
    expect(() => new RecoveryOutbox(2, 'unknown' as 'drop-oldest')).toThrow('policy');
  });
  it('expires exactly at TTL, preserving source timestamp and independent input copies', () => {
    const queue = new RecoveryOutbox(2, 'drop-oldest', 10);
    const input = metric();
    queue.enqueue([input], 1);
    queue.enqueue([metric(2)], 2);
    input.value = 99;
    const copy = queue.snapshot(5);
    copy.entries[0]?.metrics.splice(0);
    expect(queue.dequeue(10)?.[0]).toEqual(metric());
    expect(queue.dequeue(12)).toBeUndefined();
    expect(queue.statistics()).toMatchObject({ accepted: 2, expired: 1, replayed: 1 });
  });
  it('applies both overflow policies and purges expiry before capacity decisions', () => {
    const dropped = new RecoveryOutbox(1, 'drop-oldest', 10);
    dropped.enqueue([metric(1)], 0);
    expect(dropped.enqueue([metric(2)], 1)).toBe('accepted-after-drop');
    expect(dropped.statistics().droppedOldest).toBe(1);
    const rejected = new RecoveryOutbox(1, 'reject-newest', 10);
    rejected.enqueue([metric(1)], 0);
    expect(rejected.enqueue([metric(2)], 1)).toBe('rejected');
    expect(rejected.enqueue([metric(3)], 10)).toBe('accepted');
    expect(rejected.statistics()).toMatchObject({ rejectedNewest: 1, expired: 1 });
    expect(rejected.dequeue(10)?.[0]?.value).toBe(3);
  });
  it('rejects invalid batches and regressing/invalid time before mutation', () => {
    const queue = new RecoveryOutbox(1, 'drop-oldest', 10);
    queue.enqueue([metric(1)], 10);
    expect(() => queue.enqueue([], 20)).toThrow();
    expect(() => queue.enqueue([metric(2)], 9)).toThrow('clock');
    expect(() => queue.snapshot(NaN)).toThrow('clock');
    expect(() => queue.dequeue(-1)).toThrow('clock');
    expect(queue.dequeue(10)?.[0]?.value).toBe(1);
  });
  it('retains failed synchronous publication for retry without leaking callback mutation', () => {
    const queue = new RecoveryOutbox(1, 'drop-oldest');
    queue.enqueue([metric()], 0);
    expect(() =>
      queue.replayOne(1, (metrics) => {
        const first = metrics[0];
        if (first) first.value = 77;
        throw new Error('broker rejected');
      }),
    ).toThrow('broker rejected');
    expect(queue.length).toBe(1);
    expect(queue.statistics().replayed).toBe(0);
    expect(queue.replayOne(2, (metrics) => expect(metrics[0]?.value).toBe(1))).toBe(true);
    expect(
      queue.replayOne(3, () => {
        throw new Error('empty callback must not execute');
      }),
    ).toBe(false);
    expect(queue.statistics().replayed).toBe(1);
  });
  it.each(['drop-oldest', 'reject-newest'] as const)(
    'restores with expiry and capacity shrink under %s',
    (policy) => {
      const queue = new RecoveryOutbox(1, policy);
      expect(queue.restore(checkpoint(), 40)).toEqual({
        restored: 1,
        expired: 1,
        capacityDropped: 1,
      });
      expect(queue.dequeue(40)?.[0]?.value).toBe(policy === 'drop-oldest' ? 5 : 4);
      expect(queue.statistics()).toMatchObject({
        restored: 1,
        expired: 1,
        replayed: 1,
        droppedOldest: policy === 'drop-oldest' ? 1 : 0,
        rejectedNewest: policy === 'reject-newest' ? 1 : 0,
      });
      expect(() => queue.restore(checkpoint(), 40)).toThrow('pristine');
      queue.enqueue([metric(9)], 40);
      expect(queue.snapshot(40).lastOrdinal).toBe(6);
    },
  );
  it('does not extend original expiry when receiving configuration has a longer TTL', () => {
    const queue = new RecoveryOutbox(4, 'drop-oldest', 86400000);
    queue.restore(checkpoint(), 30);
    expect(queue.dequeue(110)).toBeUndefined();
    expect(queue.statistics().expired).toBe(3);
  });
  it('rejects future/duplicate restore and exhausted ordinals without consuming data', () => {
    const queue = new RecoveryOutbox(4, 'drop-oldest');
    expect(() => queue.restore(checkpoint(), 29)).toThrow('future');
    queue.enqueue([metric()], 30);
    expect(() => queue.restore(checkpoint(), 30)).toThrow('pristine');
    const exhausted = new RecoveryOutbox(4, 'drop-oldest');
    exhausted.restore({ ...checkpoint(), lastOrdinal: Number.MAX_SAFE_INTEGER }, 30);
    expect(() => exhausted.enqueue([metric()], 31)).toThrow('exhausted');
    expect(exhausted.length).toBe(3);
    expect(() =>
      new RecoveryOutbox(1, 'drop-oldest').enqueue([metric()], 8640000000000000),
    ).toThrow('exhausted');
  });
});

describe('untrusted checkpoint boundary', () => {
  it('round-trips the independent fixture and rejects malformed/oversized/unknown-schema input', () => {
    expect(readCheckpoint(JSON.stringify(checkpoint()))).toEqual(checkpoint());
    for (const input of [
      '{',
      'null',
      JSON.stringify({ ...checkpoint(), schemaVersion: 'outbox-2' }),
      ' '.repeat(MAX_CHECKPOINT_BYTES + 1),
    ]) {
      expect(() => readCheckpoint(input)).toThrow();
    }
  });
  it.each([
    'duplicate',
    'watermark',
    'future-entry',
    'zero-life',
    'long-life',
    'unknown-key',
    'metrics',
    'duplicate-name',
  ])('rejects %s corruption', (kind) => {
    const value = checkpoint();
    const first = value.entries[0];
    if (!first) throw new Error('fixture missing');
    if (kind === 'duplicate') value.entries.push(structuredClone(first));
    if (kind === 'watermark') value.lastOrdinal = 1;
    if (kind === 'future-entry') first.enqueuedAt = 31;
    if (kind === 'zero-life') first.expiresAt = first.enqueuedAt;
    if (kind === 'long-life') first.expiresAt = first.enqueuedAt + 86400001;
    if (kind === 'unknown-key') Object.assign(value, { password: 'must-not-be-imported' });
    if (kind === 'metrics') first.metrics[0] = { ...metric(), value: Infinity };
    if (kind === 'duplicate-name') value.currentMetrics.push(metric());
    expect(() => checkpointSchema.parse(value)).toThrow();
  });
});

describe('edge restart lifecycle', () => {
  it('recovers the actual cold-chain workflow with explicit loss accounting and preserved timestamps', () => {
    const rehearsal = prepareRecoveryRehearsal();
    expect(rehearsal.checkpoint).not.toContain('fixture-only');
    expect(rehearsal.recover(rehearsal.checkpoint)).toMatchObject({
      passed: true,
      restore: { expired: 1, capacityDropped: 1, restored: 2 },
      finalValue: 4.4,
    });
  });
  it('retains a rejected broker publication and exposes an explicit connected retry', () => {
    const h = harness();
    expect(() => h.node.retryBuffered()).toThrow('active');
    h.node.publishMetrics([metric(8)]);
    const publish = h.broker.publishFrom.bind(h.broker);
    let rejectData = true;
    const spy = vi.spyOn(h.broker, 'publishFrom').mockImplementation((...args) => {
      if (rejectData && args[2].endsWith('/events/data')) {
        rejectData = false;
        throw new Error('temporary broker failure');
      }
      return publish(...args);
    });
    expect(() => h.node.connect()).toThrow('temporary broker failure');
    expect(h.node.statistics()).toMatchObject({ buffered: 1, outbox: { replayed: 0 } });
    expect(h.node.retryBuffered()).toBe(1);
    expect(h.node.retryBuffered()).toBe(0);
    expect(h.node.statistics().buffered).toBe(0);
    spy.mockRestore();
  });
  it('binds identity and validates atomically before allowing a valid restore', () => {
    const { node } = harness();
    expect(() =>
      node.restoreCheckpoint(JSON.stringify({ ...checkpoint(), nodeId: 'another-node' })),
    ).toThrow('identity');
    expect(() => node.restoreCheckpoint('{')).toThrow();
    expect(node.statistics().buffered).toBe(0);
    expect(node.restoreCheckpoint(JSON.stringify(checkpoint())).restored).toBe(3);
    expect(() => node.restoreCheckpoint(JSON.stringify(checkpoint()))).toThrow('pristine');
    expect(node.statistics().buffered).toBe(3);
  });
  it('cannot import after connecting or overwrite a locally populated outbox', () => {
    const h = harness();
    h.node.connect();
    expect(() => h.node.checkpoint()).toThrow('disconnected');
    expect(() => h.node.restoreCheckpoint(JSON.stringify(checkpoint()))).toThrow('never-connected');
    h.node.disconnectGracefully();
    expect(() => h.node.restoreCheckpoint(JSON.stringify(checkpoint()))).toThrow('never-connected');
    const fresh = harness();
    fresh.node.publishMetrics([metric()]);
    expect(() => fresh.node.restoreCheckpoint(JSON.stringify(checkpoint()))).toThrow('pristine');
    expect(fresh.node.statistics().buffered).toBe(1);
  });
  it('preserves prior current state but gives replay a new birth/sequence, including modulo wrap', () => {
    const h = harness(300);
    const value = checkpoint();
    value.entries = [];
    h.node.restoreCheckpoint(JSON.stringify(value));
    for (let index = 0; index < 260; index += 1) h.node.publishMetrics([metric(index)]);
    h.consumer.connect();
    h.node.connect();
    const events = h.broker
      .publicationLog()
      .filter((item) => item.topic.endsWith('/events/data'))
      .map((item) => JSON.parse(item.payload) as { birthSequence: number; seq: number });
    expect(events).toHaveLength(260);
    expect(events.every((event) => event.birthSequence === 8)).toBe(true);
    expect(events.slice(254, 258).map((event) => event.seq)).toEqual([255, 0, 1, 2]);
    expect(
      h.consumer.store().getNode('cold-chain', 'van-07')?.metrics['cargo.temperature']?.value,
    ).toBe(259);
    expect(h.consumer.store().statistics()).toMatchObject({ invalid: 0, outOfOrder: 0, gaps: 0 });
  });
  it('expires queued data at reconnect, validates metric count and stops birth counter wrap', () => {
    const h = harness(4, 10);
    h.node.publishMetrics([metric()]);
    h.setTime(40);
    h.node.connect();
    expect(h.node.statistics().outbox).toMatchObject({ expired: 1, replayed: 0 });
    expect(() => h.node.publishMetrics([])).toThrow('1..256');
    const last = harness();
    last.node.restoreCheckpoint(JSON.stringify({ ...checkpoint(), birthSequence: 4294967294 }));
    last.node.connect();
    last.node.disconnectGracefully();
    expect(() => last.node.connect()).toThrow('exhausted');
    expect(() => last.node.checkpoint()).toThrow();
  });
});
